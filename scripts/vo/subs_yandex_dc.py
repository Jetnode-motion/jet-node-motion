"""Turn the voice-over word timings (story.json from elevenlabs_story.py) into caption chunks and
per-line times for YandexDcNews: writes src/compositions/YandexDcNews/vo.ts.

  python3 scripts/vo/subs_yandex_dc.py public/audio/yandex-dc/story.json
"""
import json, sys

OFFSET = 0.4  # the voice starts a breath after the first frame
TAIL = 1.8  # the CTA holds after the last word
MAX_CHARS = 24  # one centred line at 54 px

# Spoken spelling → on-screen spelling (multi-word names are kept in one chunk)
DISPLAY = {'Эм Видео': 'М.Видео', 'Дом ру': 'Дом.ру', 'Джетноуд ВПН': 'JetnodeVPN'}

lines = json.load(open(sys.argv[1], encoding='utf-8'))


def tokens(words):
    """Merge dashes into the previous word and multi-word names into one token."""
    out = []
    for w in words:
        if w['text'] in ('—', '–') and out:
            out[-1] = {**out[-1], 'text': out[-1]['text'] + ' —'}
            continue
        if out:
            pair = out[-1]['text'] + ' ' + w['text'].rstrip(',.?!:')
            if any(pair == k for k in DISPLAY):
                out[-1] = {'text': out[-1]['text'] + ' ' + w['text'], 'from': out[-1]['from'], 'to': w['to']}
                continue
        out.append(dict(w))
    return out


def show(text):
    for k, v in DISPLAY.items():
        text = text.replace(k, v)
    return text.rstrip(',:—').rstrip()


WEAK = {'и', 'а', 'но', 'в', 'во', 'на', 'по', 'о', 'об', 'до', 'за', 'для', 'при', 'с', 'из', 'не', 'что', 'если', 'это', 'так', 'его', 'их', 'же', 'три'}


def split_sentence(toks):
    """Best split of one sentence into caption chunks: short enough for one line, broken at
    punctuation where possible, never ending on a preposition or conjunction, evenly sized."""
    n = len(toks)
    best = [0.0] + [float('inf')] * n
    back = [0] * (n + 1)
    for j in range(1, n + 1):
        for i in range(j):
            text = show(' '.join(t['text'] for t in toks[i:j]))
            if len(text) > MAX_CHARS and j - i > 1:
                continue
            last = toks[j - 1]['text']
            cost = 22 + (len(text) - 17) ** 2 / 12
            if j < n and last[-1] not in ',:—':
                cost += 6
            if j < n and last.lower() in WEAK:
                cost += 60
            if best[i] + cost < best[j]:
                best[j], back[j] = best[i] + cost, i
    cuts, j = [], n
    while j:
        cuts.append((back[j], j))
        j = back[j]
    return [toks[i:j] for i, j in reversed(cuts)]


subs = []
for li, line in enumerate(lines):
    sentence = []
    toks = tokens(line['words'])
    for j, w in enumerate(toks):
        sentence.append(w)
        if j + 1 == len(toks) or w['text'][-1] in '.?!':
            for chunk in split_sentence(sentence):
                text = ' '.join(c['text'] for c in chunk)
                subs.append({'line': li, 'from': chunk[0]['from'], 'end': chunk[-1]['to'], 'text': show(text)})
            sentence = []

for i, s in enumerate(subs):
    nxt = subs[i + 1]['from'] if i + 1 < len(subs) else s['end'] + 1.0
    # hold until the next chunk starts, but don't linger over a long pause
    s['to'] = min(nxt, s['end'] + 0.45)

r = lambda x: round(x + OFFSET, 2)
ts = [
    '// Generated by scripts/vo/subs_yandex_dc.py from the ElevenLabs word timings. Seconds.',
    f'export const VO_OFFSET = {OFFSET};',
    '/** spoken span of each scene line, in composition time */',
    'export const VO_LINES: {from: number; to: number}[] = [',
    *[f"  {{from: {r(l['from'])}, to: {r(l['to'])}}}," for l in lines],
    '];',
    f"export const VO_END = {r(lines[-1]['to'] + TAIL)};",
    '/** caption chunks timed to the voice */',
    'export const VO_SUBS: {from: number; to: number; text: string}[] = [',
    *[f"  {{from: {r(s['from'] - 0.06)}, to: {r(s['to'])}, text: {json.dumps(s['text'], ensure_ascii=False)}}}," for s in subs],
    '];',
    '',
]
open('src/compositions/YandexDcNews/vo.ts', 'w', encoding='utf-8').write('\n'.join(ts))
for s in subs:
    print(f"{s['from'] + OFFSET:6.2f} {s['text']}")
